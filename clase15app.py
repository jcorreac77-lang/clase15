import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt

st.set_page_config(page_title="Dashboard interactivo de notas", layout="wide")

with st.sidebar:
    st.header("Mi primera barra lateral de Streamlit")
    st.write("¡Hola! Este panel lateral sirve para organizar los controles, la carga de datos y filtros.")

    st.image("uss logo.png", width=120)

    if st.button("Presionar barra"):
        st.success("¡Presionaste el botón de la barra lateral!")

    texto_lateral = st.text_input("Escribe algo en la barra")
    if texto_lateral:
        st.write(f"Contenido ingresado: {texto_lateral}")
    else:
        st.info("Escribe un mensaje en el campo de la barra lateral.")

    st.markdown("---")
    st.subheader("Datos y filtros del Dashboard")

    archivo = st.file_uploader("Carga el archivo de estudiantes", type=["csv"])

if archivo is not None:
    df = pd.read_csv(archivo)

    df.columns = df.columns.str.strip().str.lower()

    if 'nota_1' in df.columns and 'nota_2' in df.columns and 'Promedio' not in df.columns:
        df['Promedio'] = df['nota_1'] * 0.5 + df['nota_2'] * 0.5

    renombres = {
        'sexo': 'Sexo',
        'seccion': 'Sección',
        'estudiante': 'Estudiante',
        'asistencia': 'Asistencia (%)',
        'promedio': 'Promedio'
    }
    df = df.rename(columns=renombres)

    with st.sidebar:
        sexos_disponibles = df["Sexo"].unique().tolist()
        sexo_seleccionado = st.multiselect("Sexo", options=sexos_disponibles, default=sexos_disponibles)

        secciones = ["Todas"] + sorted(df["Sección"].unique().tolist())
        seccion_seleccionada = st.selectbox("Sección", options=secciones)

        rango_promedio = st.slider("Rango del promedio", min_value=1.0, max_value=7.0, value=(1.0, 7.0), step=0.1)
        asistencia_minima = st.number_input("Asistencia mínima (%)", min_value=0, max_value=100, value=0, step=1)
        st.caption("Los filtros se combinan. Quitar ambos sexos deja la selección vacía.")

    df_filtrado = df[
        (df["Sexo"].isin(sexo_seleccionado)) &
        (df["Promedio"] >= rango_promedio[0]) &
        (df["Promedio"] <= rango_promedio[1]) &
        (df["Asistencia (%)"] >= asistencia_minima)
    ]

    if seccion_seleccionada != "Todas":
        df_filtrado = df_filtrado[df_filtrado["Sección"] == seccion_seleccionada]

    st.title("Dashboard interactivo de notas")
    st.header("¡Hola! Mi primera aplicación de Streamlit")
    st.write("Explora los resultados de un curso combinando filtros. **Promedio**: 50% de cada evaluación. **Aprobación del ejercicio**: promedio mayor o igual a 4,0.")

    st.image("uss logo.png", width=120)

    col_btn, col_txt = st.columns([1, 2])
    with col_btn:
        if st.button("Haz clic"):
            st.success("¡El botón principal ha sido presionado!")
    with col_txt:
        texto_principal = st.text_input("Escribe algo")
        if texto_principal:
            st.write(f"Escribiste: {texto_principal}")

    st.markdown("---")

    sexos_txt = ", ".join(sexo_seleccionado) if sexo_seleccionado else "Ninguno"
    st.caption(f"**Filtros activos:** {sexos_txt} · **Sección:** {seccion_seleccionada} · **Promedio:** {rango_promedio[0]:.1f} a {rango_promedio[1]:.1f} · **Asistencia mínima:** {asistencia_minima}%")

    total_seleccionados = len(df_filtrado)
    promedio_general = df_filtrado["Promedio"].mean() if total_seleccionados > 0 else 0.0
    aprobacion = (df_filtrado["Promedio"] >= 4.0).mean() * 100 if total_seleccionados > 0 else 0.0

    metrica_1, metrica_2, metrica_3 = st.columns(3)
    metrica_1.metric("Estudiantes seleccionados", f"{total_seleccionados}")
    metrica_2.metric("Promedio general", f"{promedio_general:.2f}".replace(".", ","))
    metrica_3.metric("Aprobación", f"{aprobacion:.2f}%".replace(".", ","))

    col_grafico, col_checkbox = st.columns([2, 1])
    with col_grafico:
        tipo_grafico = st.radio("Gráfico", ["Notas por estudiante", "Promedio por sección"], horizontal=True)
    with col_checkbox:
        mostrar_tabla = st.checkbox("Mostrar tabla", value=True)

    if mostrar_tabla:
        contenedor_viz, contenedor_tabla = st.columns([1.2, 1])
    else:
        contenedor_viz = st.container()

    with contenedor_viz:
        st.subheader("Visualización de notas")
        if total_seleccionados > 0:
            fig, ax = plt.subplots(figsize=(7, 4))
            if tipo_grafico == "Notas por estudiante":
                df_plot = df_filtrado.sort_values("Estudiante")
                ax.bar(df_plot["Estudiante"], df_plot["Promedio"], color="#1f77b4")
                ax.set_title("Promedio por estudiante")
                ax.set_xlabel("Estudiante")
                plt.xticks(rotation=35, ha="right")
            else:
                df_plot = df_filtrado.groupby("Sección", as_index=False)["Promedio"].mean()
                ax.bar(df_plot["Sección"], df_plot["Promedio"], color="#1f77b4")
                ax.set_title("Promedio por sección")
                ax.set_xlabel("Sección")

            ax.axhline(4.0, color="red", linestyle="--", linewidth=1, label="Aprobación: 4,0")
            ax.set_ylabel("Promedio de notas")
            ax.set_ylim(0, 7)
            ax.legend()
            st.pyplot(fig)
        else:
            st.warning("No hay estudiantes que coincidan con los filtros seleccionados.")

    if mostrar_tabla:
        with contenedor_tabla:
            st.subheader("Estudiantes seleccionados")
            st.dataframe(df_filtrado, use_container_width=True, hide_index=True)

    csv_descarga = df_filtrado.to_csv(index=False).encode("utf-8")
    st.download_button(
        label="Descargar selección CSV",
        data=csv_descarga,
        file_name="estudiantes_filtrados.csv",
        mime="text/csv"
    )
    st.caption(f"Mostrando {total_seleccionados} de {len(df)} estudiantes. La asistencia solo se usa como filtro; la aprobación depende del promedio.")

else:
    st.title("Dashboard interactivo de notas")
    st.header("¡Hola! Mi primera aplicación de Streamlit")
    st.info("Por favor, carga tu archivo CSV en la barra lateral para comenzar.")
